from sqlalchemy import Column, Integer, String, Float, DateTime, Enum, Boolean, ForeignKey, Text
from sqlalchemy.orm import relationship
from database import Base
import enum
from datetime import datetime

class RoleEnum(str, enum.Enum):
    USER = "user"
    ADMIN = "admin"

class ActionEnum(str, enum.Enum):
    BUY = "BUY"
    SELL = "SELL"
    HOLD = "HOLD"

# ---------------------------------------------------------
# Core Identity Entities
# ---------------------------------------------------------
class User(Base):
    __tablename__ = "users"
    
    id = Column(Integer, primary_key=True, index=True)
    email = Column(String, unique=True, index=True, nullable=False)
    hashed_password = Column(String, nullable=False)
    full_name = Column(String, nullable=True)
    virtual_balance = Column(Float, default=100000.0, nullable=False) # Demo starting capital $100,000
    is_guest = Column(Boolean, default=False, index=True)
    role = Column(Enum(RoleEnum), default=RoleEnum.USER, index=True)
    is_blocked = Column(Boolean, default=False, index=True)
    created_at = Column(DateTime, default=datetime.utcnow, index=True)
    last_login = Column(DateTime, nullable=True)

    # Relationships
    watchlists = relationship("Watchlist", back_populates="user", cascade="all, delete-orphan")
    login_logs = relationship("LoginLog", back_populates="user", cascade="all, delete-orphan")
    admin_actions = relationship("AdminAction", back_populates="admin", cascade="all, delete-orphan")
    portfolio_items = relationship("PortfolioItem", back_populates="user", cascade="all, delete-orphan")
    transactions = relationship("Transaction", back_populates="user", cascade="all, delete-orphan")

class Stock(Base):
    __tablename__ = "stocks"
    
    id = Column(Integer, primary_key=True, index=True)
    symbol = Column(String, unique=True, index=True, nullable=False)
    company_name = Column(String, nullable=False)
    sector = Column(String, nullable=True, index=True)
    active_status = Column(Boolean, default=True, index=True)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    # Relationships
    predictions = relationship("PredictionResult", back_populates="stock")
    recommendations = relationship("Recommendation", back_populates="stock")
    watchlists = relationship("Watchlist", back_populates="stock")

# ---------------------------------------------------------
# Mapping / Joins
# ---------------------------------------------------------
class Watchlist(Base):
    __tablename__ = "watchlist"
    
    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(Integer, ForeignKey("users.id", ondelete="CASCADE"), index=True, nullable=False)
    stock_id = Column(Integer, ForeignKey("stocks.id", ondelete="CASCADE"), index=True, nullable=False)
    added_at = Column(DateTime, default=datetime.utcnow)

    # Relationships
    user = relationship("User", back_populates="watchlists")
    stock = relationship("Stock", back_populates="watchlists")

# ---------------------------------------------------------
# Machine Learning & AI Outputs
# ---------------------------------------------------------
class PredictionResult(Base):
    """Stores the literal arrays/price targets generated by the LSTM/XGBoost sequence."""
    __tablename__ = "prediction_results"
    
    id = Column(Integer, primary_key=True, index=True)
    stock_id = Column(Integer, ForeignKey("stocks.id", ondelete="CASCADE"), index=True, nullable=False)
    target_date = Column(DateTime, nullable=False, index=True)
    predicted_price = Column(Float, nullable=False)
    model_version = Column(String, nullable=True) # e.g. "LSTM_v2", "XGB_v1"
    created_at = Column(DateTime, default=datetime.utcnow, index=True)

    # Relationships
    stock = relationship("Stock", back_populates="predictions")

class Recommendation(Base):
    """Stores the final processed Signal generated by the Rec Engine (TA + ML + NLP)."""
    __tablename__ = "recommendations"
    
    id = Column(Integer, primary_key=True, index=True)
    stock_id = Column(Integer, ForeignKey("stocks.id", ondelete="CASCADE"), index=True, nullable=False)
    action = Column(Enum(ActionEnum), nullable=False, index=True)
    confidence_score = Column(Float, nullable=False)
    reasoning_text = Column(Text, nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow, index=True)

    # Relationships
    stock = relationship("Stock", back_populates="recommendations")

# ---------------------------------------------------------
# Audit & Logging (Admin Architecture)
# ---------------------------------------------------------
class LoginLog(Base):
    __tablename__ = "login_logs"
    
    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(Integer, ForeignKey("users.id", ondelete="CASCADE"), index=True, nullable=False)
    ip_address = Column(String, nullable=True)
    user_agent = Column(String, nullable=True)
    status = Column(String, nullable=False) # e.g. "SUCCESS", "FAILED"
    timestamp = Column(DateTime, default=datetime.utcnow, index=True)

    # Relationships
    user = relationship("User", back_populates="login_logs")

class AdminAction(Base):
    """Secure ledger of sensitive destructive/trigger actions taken by Admins."""
    __tablename__ = "admin_actions"
    
    id = Column(Integer, primary_key=True, index=True)
    admin_id = Column(Integer, ForeignKey("users.id", ondelete="CASCADE"), index=True, nullable=False)
    action_type = Column(String, nullable=False, index=True) # e.g. "FORCE_RETRAIN", "DELETE_USER"
    target_entity_id = Column(String, nullable=True)
    metadata_json = Column(Text, nullable=True) # Stores parameters / reason
    timestamp = Column(DateTime, default=datetime.utcnow, index=True)

    # Relationships
    admin = relationship("User", back_populates="admin_actions")

# ---------------------------------------------------------
# Paper Trading & Virtual Portfolio
# ---------------------------------------------------------
class PortfolioItem(Base):
    """Stores user stock holdings for paper trading."""
    __tablename__ = "portfolio_items"
    
    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(Integer, ForeignKey("users.id", ondelete="CASCADE"), index=True, nullable=False)
    symbol = Column(String, index=True, nullable=False)
    company_name = Column(String, nullable=True)
    shares = Column(Float, default=0.0, nullable=False)
    average_buy_price = Column(Float, default=0.0, nullable=False)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    # Relationships
    user = relationship("User", back_populates="portfolio_items")

class Transaction(Base):
    """Ledger recording virtual buy, sell, and deposit orders."""
    __tablename__ = "transactions"
    
    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(Integer, ForeignKey("users.id", ondelete="CASCADE"), index=True, nullable=False)
    symbol = Column(String, index=True, nullable=True) # None for cash deposits
    transaction_type = Column(String, nullable=False) # "BUY", "SELL", "DEPOSIT"
    shares = Column(Float, default=0.0)
    price_per_share = Column(Float, default=0.0)
    total_amount = Column(Float, nullable=False)
    timestamp = Column(DateTime, default=datetime.utcnow, index=True)

    # Relationships
    user = relationship("User", back_populates="transactions")
